#!/usr/bin/env python3
"""Regenerates the Android/iOS React-preview HTML shell from scripts/react-preview-shell.html.

The shell converts imports/exports and mounts the component *inside the WebView* (in JS), so the
mobile apps only have to inject the raw source + css as JSON. Edit the .html, then run this."""
import pathlib
root = pathlib.Path(__file__).resolve().parent.parent
tpl = (root / "scripts/react-preview-shell.html").read_text()
assert '"""' not in tpl and "${" not in tpl
kt = root / "android/app/src/main/java/com/friday/app/ui/canvas/ReactPreviewShell.kt"
kt.write_text(f'''package com.friday.app.ui.canvas

// GENERATED by scripts/gen-react-preview-shell.py from scripts/react-preview-shell.html — do not edit.
internal const val REACT_PREVIEW_SHELL = """{tpl}"""
''')
sw = root / "ios/FridayApp/Sources/UI/Canvas/ReactPreviewShell.swift"
sw.write_text(f'''// GENERATED by scripts/gen-react-preview-shell.py from scripts/react-preview-shell.html — do not edit.
enum ReactPreviewShell {{
    static let template = #"""
{tpl}
"""#
}}
''')
print("ok")
